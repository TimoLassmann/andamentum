class _CommentParts:
    """``comments.xml`` and ``commentsExtended.xml``, existing or to be created."""

    def __init__(self, parsed: ParsedDocx, package: _Package, *, create_extended: bool):
        self.package = package
        self.owner = parsed.document_part
        with zipfile.ZipFile(parsed.path) as archive:
            self.comments_name = related_part(
                archive,
                self.owner,
                type_suffix="/comments",
                fallback=_sibling(self.owner, "comments.xml"),
            )
            self.extended_name = related_part(
                archive,
                self.owner,
                type_suffix="/commentsExtended",
                fallback=_sibling(self.owner, "commentsExtended.xml"),
            )
        self.comments_new = self.comments_name is None
        if self.comments_name is None:
            self.comments_name = _sibling(self.owner, "comments.xml")
            self.comments_root = _part_root("comments")
        else:
            data = package.get(self.comments_name)
            assert data is not None
            self.comments_root = parse_xml(data)
        self.extended_new = False
        self.extended_root: Any | None = None
        if self.extended_name is not None:
            data = package.get(self.extended_name)
            assert data is not None
            self.extended_root = parse_xml(data)
        elif create_extended:
            self.extended_name = _sibling(self.owner, "commentsExtended.xml")
            self.extended_root = _part_root("commentsEx", namespace=W15_NS)
            self.extended_new = True
        self.added = 0
        self._next_id = self._first_free_id(parsed.root)
        self._used_para_ids = {
            int(value, 16)
            for root in (parsed.root, self.comments_root)
            for element in root.iter(w("p"))
            if (value := element.get(w14("paraId"))) and _is_hex(value)
        }

    def _first_free_id(self, document_root: Any) -> int:
        used = [
            int(value)
            for root in (self.comments_root, document_root)
            for element in root.iter(
                w("comment"),
                w("commentRangeStart"),
                w("commentRangeEnd"),
                w("commentReference"),
            )
            if (value := element.get(w("id"))) and value.isdigit()
        ]
        return max(used) + 1 if used else 1

    def _new_para_id(self) -> str:
        number = max(self._used_para_ids, default=0x0FFFFFFF) + 1
        if number >= _PARA_ID_LIMIT:
            raise DocxApplyError("no free w14:paraId left")
        self._used_para_ids.add(number)
        return f"{number:08X}"

    def has(self, comment_id: str) -> bool:
        return self._element(comment_id) is not None

    def _element(self, comment_id: str) -> Any | None:
        for comment in self.comments_root.iter(w("comment")):
            if comment.get(w("id")) == comment_id:
                return comment
        return None

    def _last_para_id(self, comment: Any) -> str:
        paragraphs = list(comment.iter(w("p")))
        last = paragraphs[-1]
        value = last.get(w14("paraId"))
        if not value:
            value = self._new_para_id()
            last.set(w14("paraId"), value)
        return value

    def _extended_entry(self, para_id: str, parent: str | None) -> None:
        assert self.extended_root is not None
        for existing in self.extended_root.iter(f"{{{W15_NS}}}commentEx"):
            if existing.get(w15("paraId")) == para_id:
                return
        entry = etree.SubElement(self.extended_root, f"{{{W15_NS}}}commentEx")
        entry.set(w15("paraId"), para_id)
        if parent is not None:
            entry.set(w15("paraIdParent"), parent)
        entry.set(w15("done"), "0")

    def add(
        self, writer: _Writer, text: str, author: str, *, parent: str | None = None
    ) -> int:
        comment_id = self._next_id
        self._next_id += 1
        lines = text.split("\n")
        element = XMLElementBuilder.create_comment_element(comment_id, author, lines[0])
        element.set(w("date"), writer.date)
        element.set(w("initials"), _initials(author))
        first = element.find(w("p"))
        run = etree.Element(w("r"))
        etree.SubElement(run, w("annotationRef"))
        first.insert(0, run)
        for line in lines[1:]:
            extra = etree.SubElement(element, w("p"))
            piece = etree.SubElement(etree.SubElement(extra, w("r")), w("t"))
            piece.set(f"{{{XML_NS}}}space", "preserve")
            piece.text = line
        for paragraph in element.iter(w("p")):
            paragraph.set(w14("paraId"), self._new_para_id())
        self.comments_root.append(element)
        self.added += 1
        if self.extended_root is not None:
            parent_para = None
            if parent is not None:
                parent_element = self._element(parent)
                assert parent_element is not None
                parent_para = self._last_para_id(parent_element)
                self._extended_entry(parent_para, None)
            self._extended_entry(self._last_para_id(element), parent_para)
        return comment_id

    def commit(self) -> None:
        if not self.added:
            return
        assert self.comments_name is not None
        self.package.changes[self.comments_name] = _serialize(self.comments_root)
        if self.comments_new:
            _add_relationship(
                self.package,
                owner=self.owner,
                rel_type=_COMMENTS_TYPE,
                target=_relative_target(self.comments_name, owner=self.owner),
            )
            _add_override(
                self.package, part=self.comments_name, content_type=_COMMENTS_CT
            )
        if self.extended_root is not None and self.extended_name is not None:
            self.package.changes[self.extended_name] = _serialize(self.extended_root)
            if self.extended_new:
                _add_relationship(
                    self.package,
                    owner=self.owner,
                    rel_type=_COMMENTS_EXT_TYPE,
                    target=_relative_target(self.extended_name, owner=self.owner),
                )
                _add_override(
                    self.package, part=self.extended_name, content_type=_COMMENTS_EXT_CT
                )


def _part_root(local: str, *, namespace: str = W_NS) -> Any:
    root = etree.Element(
        f"{{{namespace}}}{local}",
        nsmap={"w": W_NS, "w14": W14_NS, "w15": W15_NS, "mc": MC_NS},
    )
    root.set(f"{{{MC_NS}}}Ignorable", "w14 w15")
    return root


def _is_hex(value: str) -> bool:
    try:
        int(value, 16)
    except ValueError:
        return False
    return True


def _initials(author: str) -> str:
    letters = "".join(word[0] for word in author.split() if word[:1].isalnum())
    return (letters or "AC")[:3].upper()


