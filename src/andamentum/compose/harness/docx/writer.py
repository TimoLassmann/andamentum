class _Writer:
    """One ``apply`` call: plans, mutates the parsed tree, serialises, verifies."""

    def __init__(
        self,
        view: DocumentView,
        txn: Transaction,
        parsed: ParsedDocx,
        package: _Package,
        expansion: Expansion,
    ) -> None:
        self.expansion = expansion
        self.view = view
        self.txn = txn
        self.parsed = parsed
        self.package = package
        self.root = parsed.root
        self.elements: list[Any] = list(parsed.elements)
        self.index_of_element = {el: i for i, el in enumerate(self.elements)}
        self.ids = [p.id for p in view.paragraphs]
        self.index_of_id = {pid: i for i, pid in enumerate(self.ids)}
        self.texts = [p.text for p in view.paragraphs]
        self.starts: list[int] = []
        offset = 0
        for text in self.texts:
            self.starts.append(offset)
            offset += len(text) + 1
        self.refusals: dict[int, str] = {}
        self.touched: set[int] = set()  # paragraphs any applied op may change
        self.text_edited: set[int] = set()  # paragraphs a Replace/Insert/Delete hit
        self.edits: list[SpanEdit] = []
        self.fields: list[Field] = []
        self.edit_paragraph: dict[int, int] = {}  # id(edit) -> paragraph index
        self.applied_edits: list[SpanEdit] = []
        self.new_paragraphs: dict[int, list[str]] = {}  # after original index -> texts
        self.new_comments: list[_NewComment] = []
        self.new_anchors: list[_NewAnchor] = []
        self.date = datetime.datetime.now(datetime.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
        self.before = [
            etree.tostring(el, with_tail=False) for el in self.elements
        ]  # byte-identity baseline, taken before any change
        self.expected: list[str] = list(self.texts)
        # Citation work: the edit of each field citation, where the fields
        # went, and what the new or extended bibliography field must read as.
        self.field_edits: dict[int, FieldPlan] = {}  # id(edit) -> plan
        self.new_fields: list[tuple[int, str]] = []  # (original paragraph, display)
        self.bibliography_append: tuple[Field, SpanEdit, list[str]] | None = None
        self.bibliography_text: str | None = None  # a newly written field's result

    # ------------------------------------------------------------- helpers

    def _label(self, op: Operation) -> str:
        if isinstance(op, (Replace, Delete, CommentOp, Bind)):
            return f"{op.op} {op.paragraph_id}[{op.start}:{op.end}]"
        if isinstance(op, Insert):
            return f"insert {op.paragraph_id}@{op.at}"
        if isinstance(op, InsertParagraph):
            return f"insert_paragraph after {op.after_paragraph_id}"
        if isinstance(op, Reply):
            return f"reply to comment {op.parent_comment_id}"
        return op.op

    def _refuse(self, index: int, reason: str) -> None:
        self.refusals[index] = f"{self._label(self.txn.ops[index])}: {reason}"

    def _paragraph(self, index: int, paragraph_id: str) -> int | None:
        found = self.index_of_id.get(paragraph_id)
        if found is None:
            self._refuse(index, f"unknown paragraph {paragraph_id!r}")
        return found

    def _range(self, index: int, paragraph_id: str, start: int, end: int) -> int | None:
        found = self._paragraph(index, paragraph_id)
        if found is None:
            return None
        if end > len(self.texts[found]):
            self._refuse(
                index,
                f"range ends past the paragraph ({len(self.texts[found])} characters)",
            )
            return None
        return found

    def _has_anchor(self, paragraph: int, start: int, end: int) -> bool:
        """Is there a text character at or next to the range to hang an insertion on?"""
        atoms = self.parsed.atoms[paragraph]
        window = atoms[max(0, start - 1) : end + 1]
        return any(atom.kind is AtomKind.TEXT for atom in window)

    def _field_refusal(self, start: int, end: int) -> str | None:
        """Why an edit of ``[start, end)`` would land inside a field result."""
        if start == end:
            if any(f.start < start < f.stop for f in self.fields):
                return (
                    "insertion inside a field result, which is regenerated on refresh"
                )
            return None
        if overlapping(self.fields, start, end):
            return "range edits a field result, which is regenerated on refresh"
        return None

    # ------------------------------------------------------------- phase 1

    def plan_edits(self) -> dict[int, int]:
        """Resolve Replace/Insert/Delete into surgery edits; returns edit id -> op index."""
        origin: dict[int, int] = {}
        author = self.txn.author
        self.fields = fields_in(self.elements, document_atoms(self.elements))
        for index, op in enumerate(self.txn.ops):
            if isinstance(op, Replace | Delete):
                paragraph = self._range(index, op.paragraph_id, op.start, op.end)
                if paragraph is None:
                    continue
                current = self.texts[paragraph][op.start : op.end]
                if current != op.expect:
                    self._refuse(
                        index, f"expected {op.expect!r} but the range reads {current!r}"
                    )
                    continue
                new_text = op.text if isinstance(op, Replace) else ""
                start, end = op.start, op.end
            elif isinstance(op, Insert):
                paragraph = self._range(index, op.paragraph_id, op.at, op.at)
                if paragraph is None:
                    continue
                new_text, start, end = op.text, op.at, op.at
            else:
                continue
            if "\n" in new_text:
                self._refuse(index, "text contains a newline; use InsertParagraph")
                continue
            base = self.starts[paragraph]
            field_reason = self._field_refusal(base + start, base + end)
            if field_reason:
                self._refuse(index, field_reason)
                continue
            if new_text and not self._has_anchor(paragraph, start, end):
                self._refuse(
                    index, "no text next to the range to attach the insertion to"
                )
                continue
            edit = SpanEdit(
                span=AtomSpan(base + start, base + end),
                new_text=new_text,
                author=author,
            )
            origin[id(edit)] = index
            self.edits.append(edit)
            self.edit_paragraph[id(edit)] = paragraph
            if index in self.expansion.citation_fields:
                self.field_edits[id(edit)] = self.expansion.citation_fields[index]
        self._plan_bibliography_append()
        return origin

    def _plan_bibliography_append(self) -> None:
        """Entries to add to the document's Zotero bibliography field.

        The text goes in as a tracked insertion at the end of the field's
        result. It is not a surgery edit (surgery would put a line break in a
        new paragraph and the writer refuses edits inside field results), but
        it joins ``applied_edits`` so every later span is translated past it.
        """
        entries = self.expansion.append_entries
        if not entries:
            return
        target = next(
            (f for f in self.fields if "ZOTERO_BIBL" in field_instruction(f)), None
        )
        if target is None or target.sep is None:
            raise DocxApplyError(
                "the document has no Zotero bibliography field with a result to extend"
            )
        leading = target.stop > target.start
        text = "".join(
            (" " if position or leading else "") + entry
            for position, entry in enumerate(entries)
        )
        edit = SpanEdit(
            span=AtomSpan(target.stop, target.stop),
            new_text=text,
            author=self.txn.author,
        )
        self.edit_paragraph[id(edit)] = bisect_right(self.starts, target.stop) - 1
        self.bibliography_append = (target, edit, list(entries))

    def apply_edits(self, origin: dict[int, int]) -> None:
        if not self.edits and self.bibliography_append is None:
            return
        applied: list[SpanEdit] = []
        if self.edits:
            atoms = document_atoms(self.elements)
            first_id = next_change_id(self.root)
            report = apply_edits(TextMap(atoms), self.edits)
            self._hoist_insertions(first_id)
            for loser, _winner in report.conflicted:
                self._refuse(
                    origin[id(loser)], "overlaps another edit in this transaction"
                )
            applied = list(report.applied_edits)
            self._write_citation_fields(applied, report.insertions)
        if self.bibliography_append is not None:
            bibliography = self._write_bibliography_append()
            applied.append(bibliography)
        # Ties: the bibliography text sits inside the field, before an edit
        # that was moved to its edge.
        self.applied_edits = sorted(
            applied,
            key=lambda e: (
                e.span.start,
                self.bibliography_append is None
                or e is not self.bibliography_append[1],
            ),
        )
        # Only edits that ran count as having touched their paragraph.
        self.text_edited = {self.edit_paragraph[id(e)] for e in self.applied_edits}
        self.touched |= self.text_edited
        # The text each paragraph must now read, from the accepted edits alone.
        for edit in reversed(self.applied_edits):
            paragraph = bisect_right(self.starts, edit.span.start) - 1
            base = self.starts[paragraph]
            text = self.expected[paragraph]
            self.expected[paragraph] = (
                text[: edit.span.start - base]
                + edit.new_text
                + text[edit.span.end - base :]
            )

    def _write_citation_fields(
        self, applied: list[SpanEdit], insertions: dict[int, list[Any]]
    ) -> None:
        """Turn each applied citation insertion into a Zotero field."""
        for edit in applied:
            plan = self.field_edits.get(id(edit))
            if plan is None:
                continue
            written = insertions.get(id(edit), [])
            if len(written) != 1:
                raise DocxApplyError(
                    f"a citation insertion produced {len(written)} tracked insertions"
                )
            try:
                convert_to_field(written[0], plan)
            except ValueError as exc:
                raise DocxApplyError(f"cannot write the citation field: {exc}") from exc
            self.new_fields.append((self.edit_paragraph[id(edit)], plan.display))

    def _write_bibliography_append(self) -> SpanEdit:
        """Add the planned entries inside the bibliography field, tracked."""
        assert self.bibliography_append is not None
        target, edit, entries = self.bibliography_append
        previous = target.end.getprevious()
        rpr = previous.find(w("rPr")) if previous is not None else None
        insertion = etree.Element(w("ins"))
        insertion.set(w("id"), str(next_change_id(self.root)))
        insertion.set(w("author"), self.txn.author)
        insertion.set(w("date"), self.date)
        for run in entry_runs(entries, rpr, leading_break=target.stop > target.start):
            insertion.append(run)
        target.end.addprevious(insertion)
        return edit

    def _hoist_insertions(self, first_id: int) -> None:
        """Move each new tracked insertion out of a field result, hyperlink or
        content control it was put at the edge of.

        Surgery attaches inserted text after the character before it, which
        puts it inside whatever that character lives in. The text projection
        is the same either way (the insertion sits at the edge), so nothing
        else in the plan changes.
        """
        created = [
            element
            for element in self.root.iter(w("ins"))
            if element.getparent() is not None
            and element.getparent().tag != w("rPr")
            and (element.get(w("id")) or "").isdigit()
            and int(element.get(w("id"))) >= first_id
        ]
        if not created:
            return
        fields = fields_in(self.elements, document_atoms(self.elements))
        new = set(created)
        deleted = {
            element
            for element in self.root.iter(w("del"))
            if (element.get(w("id")) or "").isdigit()
            and int(element.get(w("id"))) >= first_id
        }
        placed: dict[
            int, XmlNode
        ] = {}  # id(anchor element) -> last element put after it
        for element in created:
            _hoist(self.root, element, fields, new, placed)
        for element in created:
            _adopt_replaced(element, deleted)

    # ------------------------------------------------------------- phase 2

    def insert_paragraphs(self) -> None:
        styles = self._style_ids()
        after: dict[int, XmlNode] = {}  # original index -> last element placed after it
        cid = next_change_id(self.root)
        for index, op in enumerate(self.txn.ops):
            if not isinstance(op, InsertParagraph):
                continue
            reference = self._paragraph(index, op.after_paragraph_id)
            if reference is None:
                continue
            if not op.text.strip() or "\n" in op.text:
                self._refuse(index, "text must be one non-empty paragraph")
                continue
            style_id = None
            if op.style is not None:
                style_id = styles.get(op.style.lower())
                if style_id is None:
                    self._refuse(index, f"style {op.style!r} is not in the document")
                    continue
            paragraph = self._new_paragraph(op.text, style_id, cid=cid)
            if index == self.expansion.new_bibliography:
                try:
                    new_bibliography_paragraph(
                        paragraph, self.expansion.new_bibliography_entries
                    )
                except ValueError as exc:
                    raise DocxApplyError(
                        f"cannot write the bibliography field: {exc}"
                    ) from exc
                self.bibliography_text = op.text
            cid += 2
            anchor = after.get(reference, self.elements[reference])
            anchor.addnext(paragraph)
            after[reference] = paragraph
            self.new_paragraphs.setdefault(reference, []).append(op.text)

    def _new_paragraph(self, text: str, style_id: str | None, *, cid: int) -> Any:
        return tracked_paragraph(
            text, author=self.txn.author, cid=cid, style_id=style_id
        )

    def _style_ids(self) -> dict[str, str]:
        return _read_style_ids(self.view.path, self.parsed, self.package)

    # ------------------------------------------------------------- phase 3

    def place_ranges(self, comments: "_CommentParts") -> None:
        """Comments and binds: resolve runs once, then write them."""
        wanted: list[tuple[int, AtomSpan]] = []
        edit_spans = [e.span for e in self.applied_edits]
        bind_spans: list[AtomSpan] = []
        known_anchors = {a.id for a in self.view.anchors}
        for index, op in enumerate(self.txn.ops):
            if not isinstance(op, CommentOp | Bind):
                continue
            paragraph = self._range(index, op.paragraph_id, op.start, op.end)
            if paragraph is None:
                continue
            base = self.starts[paragraph]
            original = AtomSpan(base + op.start, base + op.end)
            if isinstance(op, Bind):
                if op.anchor_id in known_anchors:
                    self._refuse(index, f"anchor {op.anchor_id!r} already exists")
                    continue
                known_anchors.add(op.anchor_id)
                if any(
                    s.start < original.end and original.start < s.end
                    for s in edit_spans
                ):
                    self._refuse(index, "range overlaps an edit in this transaction")
                    continue
                if any(
                    s.start < original.end and original.start < s.end
                    for s in bind_spans
                ):
                    self._refuse(
                        index, "range overlaps another bind in this transaction"
                    )
                    continue
                bind_spans.append(original)
            span = translate_span(original, self.applied_edits)
            if len(span) == 0:
                self._refuse(index, "nothing is left of the range to anchor to")
                continue
            wanted.append((index, span))
        if not wanted:
            return

        atoms = document_atoms(self.elements)
        global_text = "\n".join(self.expected)
        if "".join(a.char for a in atoms) != global_text:
            raise DocxApplyError(
                "the edited document does not read as the planned text; nothing written"
            )
        wanted = self._around_fields(
            wanted, fields_in(self.elements, atoms), global_text
        )
        if not wanted:
            return
        # Decide on the tree as it is: splitting a run is invisible in the
        # text but changes the paragraph's XML, and a refused op must leave it
        # byte-identical. Splitting keeps a run's parent, so these checks hold
        # after the cut too.
        survivors: list[tuple[int, AtomSpan]] = []
        early_fields = fields_in(self.elements, atoms)
        early_order = {element: i for i, element in enumerate(self.root.iter())}
        for index, span in wanted:
            bounds = run_bounds(atoms, span)
            if bounds is None:
                self._refuse(index, "the range holds no text to anchor to")
                continue
            if isinstance(self.txn.ops[index], Bind):
                reason = _bind_problem(
                    *_outside_fields(bounds, early_fields, early_order)
                )
                if reason:
                    self._refuse(index, reason)
                    continue
            survivors.append((index, span))
        if not survivors:
            return
        split_at_boundaries(atoms, [span for _, span in survivors])
        atoms = document_atoms(self.elements)
        resolved: list[_Resolved] = []
        fields = fields_in(self.elements, atoms)
        order = {element: i for i, element in enumerate(self.root.iter())}
        for index, span in survivors:
            bounds = run_bounds(atoms, span)
            if bounds is None:
                raise DocxApplyError("a range lost its runs while being split")
            resolved.append(
                _Resolved(
                    op_index=index,
                    span=span,
                    bounds=_outside_fields(bounds, fields, order),
                )
            )

        # Comments first: their markers go outside any control a bind then
        # puts around the same runs.
        for item in resolved:
            op = self.txn.ops[item.op_index]
            if isinstance(op, CommentOp):
                self._write_comment(comments, op, item)
        sdt_id = _next_sdt_id(self.root)
        for item in resolved:
            op = self.txn.ops[item.op_index]
            if isinstance(op, Bind):
                _wrap_in_control(op, *item.bounds, sdt_id=sdt_id)
                sdt_id += 1
                self.new_anchors.append(
                    _NewAnchor(anchor_id=op.anchor_id, kind=op.kind, span=item.span)
                )
                self._touch_range(item.bounds)

    def _around_fields(
        self,
        wanted: list[tuple[int, AtomSpan]],
        fields: list[Field],
        text: str,
    ) -> list[tuple[int, AtomSpan]]:
        """Widen comment ranges over the field results they touch; refuse what
        cannot be placed outside a field."""
        kept: list[tuple[int, AtomSpan]] = []
        for index, span in wanted:
            if not overlapping(fields, span.start, span.end):
                kept.append((index, span))
                continue
            if isinstance(self.txn.ops[index], Bind):
                if any(
                    not (span.start <= f.start and f.stop <= span.end)
                    for f in overlapping(fields, span.start, span.end)
                ):
                    self._refuse(
                        index,
                        "range cuts a field result, which is regenerated on refresh",
                    )
                    continue
                kept.append((index, span))
                continue
            start, end = widen_over_fields(fields, span.start, span.end)
            # A comment range that crosses paragraphs reads back cut at the end
            # of the first one; the markers still go around the whole field
            # (``_outside_fields`` widens the end run to the field's last run).
            end = (
                min(end, start + text[start:end].find("\n"))
                if "\n" in text[start:end]
                else end
            )
            if end <= start:
                self._refuse(index, "nothing is left of the range outside the field")
                continue
            kept.append((index, AtomSpan(start, end)))
        return kept

    def _touch_range(self, bounds: tuple[Any, Any]) -> None:
        for run in bounds:
            self._touch(run)

    def _touch(self, element: Any) -> None:
        parent = element
        while parent is not None:
            found = self.index_of_element.get(parent)
            if found is not None:
                self.touched.add(found)
                return
            parent = parent.getparent()

    def _write_comment(
        self, comments: "_CommentParts", op: CommentOp, item: _Resolved
    ) -> None:
        start_run, end_run = item.bounds
        comment_id = comments.add(self, op.text, self.txn.author)
        start, end, reference = XMLElementBuilder.create_comment_range_elements(
            comment_id
        )
        end_parent = end_run.getparent()
        position = end_parent.index(end_run)
        end_parent.insert(position + 1, end)
        end_parent.insert(position + 2, reference)
        start_parent = start_run.getparent()
        start_parent.insert(start_parent.index(start_run), start)
        self._touch_range(item.bounds)
        paragraph = bisect_right(self.starts_expected(), item.span.start) - 1
        self.new_comments.append(
            _NewComment(
                comment_id=comment_id,
                author=self.txn.author,
                text=op.text,
                para_index=paragraph,
                span=item.span,
                thread_root=None,
            )
        )

    def _latest_thread_markers(
        self, by_id: dict[str, Comment], root_id: str
    ) -> tuple[Any, Any, Any] | None:
        """Markers of the thread member that sits last in the document.

        New replies go after it, so a thread reads in the order it was written.
        The root must itself be anchored, or there is nothing to reply at.
        """
        if _thread_markers(self.root, root_id) is None:
            return None
        nodes = list(self.root.iter())  # keeps the element proxies alive
        order = {el: i for i, el in enumerate(nodes)}
        latest: tuple[Any, Any, Any] | None = None
        for member in by_id.values():
            if member.id != root_id and _root_of(by_id, member.id) != root_id:
                continue
            found = _thread_markers(self.root, member.id)
            if found is not None and (
                latest is None or order[found[2]] > order[latest[2]]
            ):
                latest = found
        return latest

    def starts_expected(self) -> list[int]:
        """Global start offset of each original paragraph in the edited text."""
        starts: list[int] = []
        offset = 0
        for text in self.expected:
            starts.append(offset)
            offset += len(text) + 1
        return starts

    # ------------------------------------------------------------- phase 4

    def write_replies(self, comments: "_CommentParts") -> None:
        by_id = {c.id: c for c in self.view.comments}
        last: dict[
            str, tuple[Any, Any, Any]
        ] = {}  # root id -> last start, end, reference
        for index, op in enumerate(self.txn.ops):
            if not isinstance(op, Reply):
                continue
            parent = by_id.get(op.parent_comment_id)
            if parent is None:
                self._refuse(index, "no such comment")
                continue
            root_id = _root_of(by_id, parent.id)
            if root_id not in last:
                found = self._latest_thread_markers(by_id, root_id)
                if found is None:
                    self._refuse(
                        index, "the comment has no anchor in the body to reply at"
                    )
                    continue
                last[root_id] = found
            if not comments.has(root_id):
                self._refuse(index, "the comment is not in comments.xml")
                continue
            reply_id = comments.add(self, op.text, self.txn.author, parent=root_id)
            start, end, reference = XMLElementBuilder.create_comment_range_elements(
                reply_id
            )
            last_start, last_end, last_ref = last[root_id]
            last_start.addnext(start)
            last_end.addnext(end)
            last_ref.addnext(reference)
            last[root_id] = (start, end, reference)
            for marker in (start, end, reference):
                self._touch(marker)
            self.new_comments.append(
                _NewComment(
                    comment_id=reply_id,
                    author=self.txn.author,
                    text=op.text,
                    para_index=-1,
                    span=None,
                    thread_root=root_id,
                )
            )


def _read_style_ids(
    path: Path, parsed: ParsedDocx, package: _Package
) -> dict[str, str]:
    """Lower-cased style name and id -> style id, from ``styles.xml``."""
    with zipfile.ZipFile(path) as archive:
        part = related_part(
            archive,
            parsed.document_part,
            type_suffix="/styles",
            fallback=_sibling(parsed.document_part, "styles.xml"),
        )
    data = package.get(part) if part else None
    if data is None:
        return {}
    found: dict[str, str] = {}
    for style in parse_xml(data).iter(w("style")):
        style_id = style.get(w("styleId"))
        if not style_id:
            continue
        found[style_id.lower()] = style_id
        name = style.find(w("name"))
        if name is not None and name.get(w("val")):
            found[name.get(w("val")).lower()] = style_id
    return found


def _root_of(by_id: dict[str, Comment], comment_id: str) -> str:
    """The id of the first comment of *comment_id*'s thread."""
    seen = {comment_id}
    while True:
        parent = by_id[comment_id].parent_id
        if parent is None or parent in seen or parent not in by_id:
            return comment_id
        seen.add(parent)
        comment_id = parent


def _sibling(part: str, name: str) -> str:
    folder = part.rpartition("/")[0]
    return f"{folder}/{name}" if folder else name


def _thread_markers(root: Any, comment_id: str) -> tuple[Any, Any, Any] | None:
    """The range start, range end and reference run of a comment, or None."""
    start = end = reference = None
    for element in root.iter(
        w("commentRangeStart"), w("commentRangeEnd"), w("commentReference")
    ):
        if element.get(w("id")) != comment_id:
            continue
        if element.tag == w("commentRangeStart"):
            start = element
        elif element.tag == w("commentRangeEnd"):
            end = element
        else:
            reference = element.getparent()  # the w:r holding the reference
    if start is None or end is None or reference is None or reference.tag != w("r"):
        return None
    return start, end, reference


def _outside_fields(
    bounds: tuple[Any, Any], fields: list[Field], order: dict[Any, int]
) -> tuple[Any, Any]:
    """Widen a run range so its ends are not inside a field result.

    An end run that lies in a field's result is replaced by the field's own
    first (or last) element, the outermost field first; a marker or control
    placed there sits around the field, not in the text Word regenerates.
    """

    def outermost(element: Any) -> Field | None:
        best: Field | None = None
        for f in fields:
            if f.simple:
                inside = element is f.begin or any(
                    a is f.begin for a in element.iterancestors()
                )
            elif f.sep is None:
                continue
            else:
                inside = order[f.sep] < order[element] < order[f.end]
            if inside and (best is None or order[f.begin] < order[best.begin]):
                best = f
        return best

    start_run, end_run = bounds
    first = outermost(start_run)
    last = outermost(end_run)
    return (
        first.begin if first is not None else start_run,
        last.end if last is not None else end_run,
    )


_CONTAINERS = frozenset({"hyperlink", "sdtContent", "fldSimple", "smartTag"})


def _hoist(
    root: Any,
    element: Any,
    fields: list[Field],
    new: set[Any],
    placed: dict[int, XmlNode],
) -> None:
    """Move the tracked insertion *element* out of every container it is at the
    edge of (innermost first); leave it where text lies on both sides."""
    while True:
        order = {el: i for i, el in enumerate(root.iter())}
        texts = sorted(
            (order[t], t)
            for t in root.iter(w("t"))
            if not any(a in new for a in t.iterancestors(w("ins")))
        )
        positions = [pos for pos, _ in texts]
        here = order[element]
        # (low, high, element that bounds the unit at its start, at its end)
        best: tuple[int, int, Any, Any] | None = None
        for ancestor in element.iterancestors():
            if ancestor.tag == w("p"):
                break
            local = ancestor.tag.rpartition("}")[2]
            if local not in _CONTAINERS:
                continue
            unit = ancestor.getparent() if local == "sdtContent" else ancestor
            high = order[list(unit.iter())[-1]] + 1
            candidate = (order[unit], high, unit, unit)
            if best is None or candidate[0] > best[0]:
                best = candidate
        for f in fields:
            if f.simple or f.sep is None:
                continue
            if order[f.sep] < here < order[f.end] and (
                best is None or order[f.sep] > best[0]
            ):
                best = (order[f.sep], order[f.end], f.begin, f.end)
        if best is None:
            return
        low, high, unit_start, unit_end = best
        after = bisect_right(positions, here)
        has_after = after < len(positions) and positions[after] < high
        has_before = (bisect_left(positions, here) - 1) >= 0 and positions[
            bisect_left(positions, here) - 1
        ] > low
        if has_after and has_before:
            return
        if not has_after:
            target = unit_end
            donor = next((t for pos, t in texts if pos >= high), None)
            if donor is None:
                donor = next(
                    (t for pos, t in reversed(texts) if pos < order[unit_start]), None
                )
            while target.getparent().tag in (w("ins"), w("moveTo")):
                target = target.getparent()
            key = id(target)
            (placed.get(key, target)).addnext(element)
            placed[key] = element
        else:
            target = unit_start
            donor = next(
                (t for pos, t in reversed(texts) if pos < order[unit_start]), None
            )
            if donor is None:
                donor = next((t for pos, t in texts if pos >= high), None)
            while target.getparent().tag in (w("ins"), w("moveTo")):
                target = target.getparent()
            target.addprevious(element)
        _restyle(element, donor.getparent() if donor is not None else None)


def _adopt_replaced(insertion: Any, deleted: set[Any]) -> None:
    """Move a replacement's insertion into the content control that holds the
    text it replaces.

    Surgery attaches inserted text after the character before it, so a
    replacement of a whole control's text lands just before the control while
    the deletion stays inside, leaving the control with no live text and the
    anchor empty. When the next element is a control whose content starts with
    a deletion of this transaction, the insertion goes first into that content,
    with the run properties of the text it replaces.
    """
    following = insertion.getnext()
    if following is None or following.tag != w("sdt"):
        return
    content = following.find(w("sdtContent"))
    if content is None:
        return
    # A comment range may open inside the control, ahead of the deletion.
    markers = (w("commentRangeStart"), w("bookmarkStart"))
    position = 0
    while position < len(content) and content[position].tag in markers:
        position += 1
    if position == len(content) or content[position] not in deleted:
        return
    first_run = content[position].find(w("r"))
    content.insert(position, insertion)
    _restyle(insertion, first_run)


def _restyle(insertion: Any, donor_run: Any | None) -> None:
    """Give the runs of *insertion* the run properties of *donor_run* (none
    when there is no text outside to copy from)."""
    for run in insertion.iter(w("r")):
        old = run.find(w("rPr"))
        if old is not None:
            run.remove(old)
        if donor_run is not None:
            properties = donor_run.find(w("rPr"))
            if properties is not None:
                run.insert(0, copy.deepcopy(properties))


def _bind_problem(start_run: Any, end_run: Any) -> str | None:
    """Why a control cannot wrap ``start_run``..``end_run``, or None if it can."""
    parent = start_run.getparent()
    if end_run.getparent() is not parent:
        return "range crosses a tracked-change, link or control boundary"
    siblings = list(parent)
    nodes = siblings[siblings.index(start_run) : siblings.index(end_run) + 1]
    depth = 0
    for node in nodes:
        for mark in node.iter(w("fldChar")):
            kind = mark.get(w("fldCharType"))
            if kind == "begin":
                depth += 1
            elif kind == "end":
                depth -= 1
                if depth < 0:
                    return "range cuts a field"
    if depth != 0:
        return "range cuts a field"
    return None


def _next_sdt_id(root: Any) -> int:
    used = [
        int(element.get(w("val")))
        for element in root.iter(w("id"))
        if element.getparent() is not None
        and element.getparent().tag == w("sdtPr")
        and (element.get(w("val")) or "").lstrip("-").isdigit()
    ]
    return max(used) + 1 if used else 1


def _wrap_in_control(op: Bind, start_run: Any, end_run: Any, *, sdt_id: int) -> None:
    parent = start_run.getparent()
    siblings = list(parent)
    first = siblings.index(start_run)
    nodes = siblings[first : siblings.index(end_run) + 1]
    sdt = etree.Element(w("sdt"))
    properties = etree.SubElement(sdt, w("sdtPr"))
    etree.SubElement(properties, w("alias")).set(w("val"), op.kind)
    etree.SubElement(properties, w("tag")).set(w("val"), anchor_tag(op.anchor_id))
    etree.SubElement(properties, w("id")).set(w("val"), str(sdt_id))
    etree.SubElement(properties, w15("appearance")).set(w15("val"), "hidden")
    content = etree.SubElement(sdt, w("sdtContent"))
    parent.insert(first, sdt)
    for node in nodes:
        content.append(node)


