class DocxAdapter:
    """The ``.docx`` implementation of the kernel's ``DocumentAdapter`` protocol."""

    def open(self, path: Path) -> DocumentView:
        from .reader import open_docx

        return open_docx(path)

    def apply(
        self, view: DocumentView, txn: Transaction, *, output: Path
    ) -> ApplyResult:
        """Write *txn* to *output*; the input is never changed.

        Raises ``NotImplementedError`` for ``Move`` / ``Unbind``, ``ValueError``
        when *view* is not the current state of ``view.path`` or *output* is the
        input, and :class:`DocxApplyError` when the written file fails its checks.
        """
        for op in txn.ops:
            if isinstance(op, Move | Unbind):
                raise NotImplementedError(
                    f"the docx writer does not implement {op.op!r}"
                )
        source = view.path
        if output.resolve() == source.resolve():
            raise ValueError(
                "output must not be the input file; apply never edits in place"
            )
        parsed = parse_docx(source)
        current = [(p.id, p.text) for p in parsed.view.paragraphs]
        if current != [(p.id, p.text) for p in view.paragraphs]:
            raise ValueError(
                f"the view is stale: {source} no longer has the paragraphs it was read with"
            )
        package = _read_package(source)
        style_ids = _read_style_ids(source, parsed, package)
        # A citation the writer refuses must not leave its work in the
        # bibliography: plan again without it, until no citation is refused.
        dropped: dict[int, str] = {}
        while True:
            expansion = expand_citations(
                view, txn, style_ids=style_ids, skip=frozenset(dropped)
            )
            writer = _Writer(view, expansion.txn, parsed, package, expansion)
            origin = writer.plan_edits()
            refused_citations = {
                expansion.origin[i]: message
                for i, message in writer.refusals.items()
                if isinstance(txn.ops[expansion.origin[i]], InsertCitation)
            }
            if not refused_citations:
                break
            dropped.update(refused_citations)
            parsed = parse_docx(source)
            package = _read_package(source)
        writer.apply_edits(origin)
        writer.insert_paragraphs()
        comments = _CommentParts(
            parsed,
            package,
            create_extended=any(isinstance(op, Reply) for op in txn.ops),
        )
        writer.place_ranges(comments)
        writer.write_replies(comments)
        comments.commit()
        package.changes[parsed.document_part] = _serialize(parsed.root)
        package.write(output)
        try:
            untouched = _verify(writer, output)
        except Exception:
            output.unlink(missing_ok=True)
            raise
        refused = {expansion.origin[i]: m for i, m in writer.refusals.items()}
        refused.update(dropped)
        return ApplyResult(
            output=output,
            applied=len(txn.ops) - len(refused),
            refused=[refused[i] for i in sorted(refused)],
            untouched=untouched,
        )

    def write_project_id(self, path: Path, *, project_id: str, output: Path) -> Path:
        """Record *project_id* in a custom XML part of a copy of *path*.

        An id already in the file must equal *project_id*; replacing one is
        refused (``ValueError``) because the id ties the file to its project folder.
        """
        if output.resolve() == path.resolve():
            raise ValueError("output must not be the input file; never edit in place")
        if not project_id.strip() or any(c in project_id for c in '<>&"\n'):
            raise ValueError(f"unusable project id {project_id!r}")
        with zipfile.ZipFile(path) as archive:
            existing = read_project_id(archive)
        if existing is not None and existing != project_id:
            raise ValueError(f"{path} already belongs to project {existing!r}")
        package = _read_package(path)
        if existing is None:
            _add_project_part(package, parse_docx(path).document_part, project_id)
        package.write(output)
        with zipfile.ZipFile(output) as archive:
            if read_project_id(archive) != project_id:
                output.unlink(missing_ok=True)
                raise DocxApplyError("the project id did not read back from the output")
        try:
            import docx

            docx.Document(str(output))
        except Exception as exc:  # noqa: BLE001 - any failure to open is the finding
            output.unlink(missing_ok=True)
            raise DocxApplyError(
                f"the output does not open in python-docx: {exc}"
            ) from exc
        return output


def _add_project_part(package: _Package, document_part: str, project_id: str) -> None:
    names = package.names()
    number = 1
    while f"customXml/item{number}.xml" in names:
        number += 1
    item = f"customXml/item{number}.xml"
    props = f"customXml/itemProps{number}.xml"
    guid = str(
        uuid.uuid5(uuid.NAMESPACE_URL, f"urn:andamentum:harness:{project_id}")
    ).upper()
    package.changes[item] = project_id_part_xml(project_id)
    package.changes[props] = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        f'<ds:datastoreItem ds:itemID="{{{guid}}}" '
        'xmlns:ds="http://schemas.openxmlformats.org/officeDocument/2006/customXml">'
        f'<ds:schemaRefs><ds:schemaRef ds:uri="{HARNESS_NS}"/></ds:schemaRefs>'
        "</ds:datastoreItem>"
    ).encode()
    package.changes[_rels_name(item)] = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        f'<Relationships xmlns="{REL_NS}">'
        f'<Relationship Id="rId1" Type="{_CUSTOM_XML_PROPS_TYPE}" Target="itemProps{number}.xml"/>'
        "</Relationships>"
    ).encode()
    _add_override(package, part=props, content_type=_CUSTOM_PROPS_CT)
    _add_relationship(
        package,
        owner=document_part,
        rel_type=_CUSTOM_XML_TYPE,
        target=f"../{item}" if "/" in document_part else item,
    )


