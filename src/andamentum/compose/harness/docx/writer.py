def _verify(writer: _Writer, output: Path) -> UntouchedReport:
    """Re-read *output* and compare it with what the transaction should have made."""
    try:
        import docx  # python-docx

        docx.Document(str(output))
    except Exception as exc:  # noqa: BLE001 - any failure to open is the finding
        raise DocxApplyError(f"the output does not open in python-docx: {exc}") from exc

    result = parse_docx(output)
    view = result.view

    layout: list[int | str] = []  # original index, or the text of an inserted paragraph
    for index in range(len(writer.texts)):
        layout.append(index)
        layout.extend(writer.new_paragraphs.get(index, []))
    if len(view.paragraphs) != len(layout):
        raise DocxApplyError(
            f"the output has {len(view.paragraphs)} paragraphs, expected {len(layout)}"
        )

    out_index: dict[int, int] = {}
    wrong_target: list[str] = []
    changed_outside: list[str] = []
    not_identical: list[str] = []
    for position, item in enumerate(layout):
        actual = view.paragraphs[position].text
        if isinstance(item, str):
            if actual != item:
                wrong_target.append(view.paragraphs[position].id)
            continue
        out_index[item] = position
        if item in writer.text_edited:
            if actual != writer.expected[item]:
                wrong_target.append(writer.ids[item])
        elif actual != writer.texts[item]:
            changed_outside.append(writer.ids[item])
        if item not in writer.touched:
            if (
                etree.tostring(result.elements[position], with_tail=False)
                != writer.before[item]
            ):
                not_identical.append(writer.ids[item])
    if wrong_target:
        raise DocxApplyError(
            f"targeted paragraphs do not read as intended: {wrong_target}"
        )
    if changed_outside:
        raise DocxApplyError(
            f"paragraphs outside the operations changed: {changed_outside}"
        )
    if not_identical:
        raise DocxApplyError(
            f"untouched paragraphs are not byte-identical to the input: {not_identical}"
        )

    expected_starts = writer.starts_expected()
    expected_text = "\n".join(writer.expected)

    def locate(span: AtomSpan) -> tuple[int, int, int]:
        paragraph = bisect_right(expected_starts, span.start) - 1
        base = expected_starts[paragraph]
        return paragraph, span.start - base, span.end - base

    by_id = {c.id: c for c in view.comments}
    for new in writer.new_comments:
        found = by_id.get(str(new.comment_id))
        if found is None:
            raise DocxApplyError(f"comment {new.comment_id} is missing from the output")
        if found.text != new.text or found.author != new.author:
            raise DocxApplyError(f"comment {new.comment_id} reads back differently")
        if new.thread_root is not None:
            root = by_id.get(new.thread_root)
            if found.parent_id != new.thread_root or root is None:
                raise DocxApplyError(
                    f"reply {new.comment_id} is not threaded to {new.thread_root}"
                )
            where = (root.paragraph_id, root.start, root.end)
            if (found.paragraph_id, found.start, found.end) != where:
                raise DocxApplyError(
                    f"reply {new.comment_id} is not anchored with its thread"
                )
            continue
        assert new.span is not None
        paragraph, start, end = locate(new.span)
        out_paragraph = view.paragraphs[out_index[paragraph]]
        anchored = out_paragraph.text[found.start : found.end]
        if (
            found.paragraph_id != out_paragraph.id
            or found.start != start
            or anchored != expected_text[new.span.start : new.span.end]
        ):
            raise DocxApplyError(
                f"comment {new.comment_id} is not anchored where requested"
            )
    for new_anchor in writer.new_anchors:
        matches = [a for a in view.anchors if a.id == new_anchor.anchor_id]
        if len(matches) != 1:
            raise DocxApplyError(
                f"anchor {new_anchor.anchor_id!r} found {len(matches)} times"
            )
        paragraph, start, end = locate(new_anchor.span)
        out_paragraph = view.paragraphs[out_index[paragraph]]
        found_anchor = matches[0]
        if (
            found_anchor.kind != new_anchor.kind
            or found_anchor.paragraph_id != out_paragraph.id
            or (found_anchor.start, found_anchor.end) != (start, end)
        ):
            raise DocxApplyError(
                f"anchor {new_anchor.anchor_id!r} is not where requested"
            )
    _verify_citations(writer, view, out_index)
    return UntouchedReport(ok=True, changed_outside=[])


def _zotero_citations(view: DocumentView, position_of: dict[str, int]) -> Counter:
    """``(paragraph position, display)`` of every well-formed Zotero citation field."""
    return Counter(
        (position_of[token.paragraph_id], token.display)
        for token in view.fields
        if token.kind == "citation"
        and token.manager == "zotero"
        and "parse_error" not in token.data
        and isinstance(token.data.get("citationItems"), list)
    )


def _verify_citations(
    writer: _Writer, view: DocumentView, out_index: dict[int, int]
) -> None:
    """Citation fields and the bibliography read back as written."""
    if writer.new_fields:
        before = _zotero_citations(
            writer.view,
            {p.id: out_index[i] for i, p in enumerate(writer.view.paragraphs)},
        )
        after = _zotero_citations(
            view, {p.id: i for i, p in enumerate(view.paragraphs)}
        )
        expected = Counter((out_index[i], d) for i, d in writer.new_fields)
        missing = expected - (after - before)
        if missing:
            raise DocxApplyError(
                f"citation fields missing from the output: {sorted(missing)}"
            )
    bibliographies = [
        token
        for token in view.fields
        if token.kind == "bibliography" and token.manager == "zotero"
    ]
    if writer.bibliography_text is not None and not any(
        token.display == writer.bibliography_text for token in bibliographies
    ):
        raise DocxApplyError("the new bibliography field is missing from the output")
    if writer.bibliography_append is not None:
        entries = writer.bibliography_append[2]
        if not any(
            all(entry in token.display for entry in entries) for token in bibliographies
        ):
            raise DocxApplyError(
                "the bibliography field does not hold the entries that were added"
            )


