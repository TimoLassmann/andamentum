@dataclass
class _Package:
    """Every part of the source archive, in order, plus the parts to change."""

    entries: list[tuple[zipfile.ZipInfo, bytes]]
    changes: dict[str, bytes] = field(default_factory=dict)

    def names(self) -> set[str]:
        return {info.filename for info, _ in self.entries} | set(self.changes)

    def get(self, name: str) -> bytes | None:
        if name in self.changes:
            return self.changes[name]
        for info, data in self.entries:
            if info.filename == name:
                return data
        return None

    def write(self, output: Path) -> None:
        output.parent.mkdir(parents=True, exist_ok=True)
        written: set[str] = set()
        with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
            for info, data in self.entries:
                archive.writestr(info, self.changes.get(info.filename, data))
                written.add(info.filename)
            for name, data in self.changes.items():
                if name not in written:
                    archive.writestr(name, data)


def _read_package(path: Path) -> _Package:
    with zipfile.ZipFile(path) as archive:
        return _Package(
            entries=[(info, archive.read(info)) for info in archive.infolist()]
        )


def _serialize(root: Any) -> bytes:
    return etree.tostring(root, xml_declaration=True, encoding="UTF-8", standalone=True)


def _rels_name(part: str) -> str:
    folder, _, name = part.rpartition("/")
    return f"{folder}/_rels/{name}.rels" if folder else f"_rels/{name}.rels"


def _relative_target(part: str, *, owner: str) -> str:
    """The relationship target for *part*, relative to the folder of *owner*."""
    owner_folder = owner.rpartition("/")[0]
    prefix = f"{owner_folder}/" if owner_folder else ""
    return part[len(prefix) :] if part.startswith(prefix) else "/" + part


def _add_relationship(
    package: _Package, *, owner: str, rel_type: str, target: str
) -> None:
    name = _rels_name(owner)
    existing = package.get(name)
    root = (
        parse_xml(existing)
        if existing is not None
        else etree.Element(f"{{{REL_NS}}}Relationships", nsmap={None: REL_NS})
    )
    used = {rel.get("Id") for rel in root}
    number = 1
    while f"rIdAm{number}" in used:
        number += 1
    etree.SubElement(
        root,
        f"{{{REL_NS}}}Relationship",
        Id=f"rIdAm{number}",
        Type=rel_type,
        Target=target,
    )
    package.changes[name] = _serialize(root)


def _add_override(package: _Package, *, part: str, content_type: str) -> None:
    existing = package.get(_CONTENT_TYPES)
    if existing is None:
        raise DocxApplyError(f"the package has no {_CONTENT_TYPES}")
    root = parse_xml(existing)
    name = "/" + part
    for override in root.iter(f"{{{CT_NS}}}Override"):
        if override.get("PartName") == name:
            return
    etree.SubElement(
        root, f"{{{CT_NS}}}Override", PartName=name, ContentType=content_type
    )
    package.changes[_CONTENT_TYPES] = _serialize(root)


