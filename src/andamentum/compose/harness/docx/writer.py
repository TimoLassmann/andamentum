"""Write a :class:`~andamentum.compose.harness.kernel.Transaction` into a ``.docx``.

``DocxAdapter.apply`` never edits its input: it reads the file, applies the
operations to the parsed XML, writes a new package and then **re-reads that
package to check its own work**. A check that fails raises
:class:`DocxApplyError` and removes the output; nothing degrades silently.

How each operation is written
    ``Replace`` / ``Insert`` / ``Delete``
        Tracked changes through whetstone's surgery (``apply_edits``): only the
        runs a range covers are cut, every other node stays where it is. The
        author is the transaction's author. Overlapping edits are refused by
        the surgery and listed in ``ApplyResult.refused``.
    ``InsertParagraph``
        A new ``w:p`` after the reference paragraph whose mark and content are
        tracked insertions, so rejecting the change removes the paragraph. Its
        style is looked up by name or id in ``styles.xml``; absent means the
        document's default style.
    ``CommentOp``
        ``commentRangeStart/End`` plus a reference run around the runs the
        range covers (whetstone's marker builder), and a ``w:comment`` in
        ``comments.xml``. Runs are split at the range boundaries only.
    ``Reply``
        A comment anchored at the same place as the thread's first comment,
        linked through ``commentsExtended.xml`` (``w15:paraIdParent``). A reply
        to a reply joins the root comment's thread.
    ``Bind``
        The range's runs wrapped in a hidden ``w:sdt`` tagged ``am:<anchor_id>``
        with ``w:alias`` set to the anchor kind (the reader reads the kind
        from the alias) and ``w15:appearance`` hidden.

Fields
    A field result (a Zotero or EndNote citation, a ``REF``) is regenerated by
    Word or the reference manager on refresh, so nothing is written inside one.
    A ``Replace`` / ``Delete`` whose range shares a character with a field
    result is refused, as is an ``Insert`` strictly inside a result. An
    ``Insert`` at the edge of a field result (or of a hyperlink or content
    control) is moved outside it and takes the run formatting of the text
    beside it, so it neither vanishes on refresh nor inherits superscript or
    link formatting. A ``CommentOp`` that touches a field result is widened to
    the whole result and its markers go around the field's first and last run
    (a field that spans paragraphs reads back cut at the end of its first).
    A ``Bind`` that cuts a field result is refused; one that covers it wraps
    the whole field.

Coordinates
    Every range is ``(paragraph_id, start, end)`` on the view text, that is, on
    the document as Word shows it with changes accepted. Edits are applied
    first; comment and bind ranges are then translated by the exact length
    change of the edits before them (``translate_span``), so a comment on text
    that a ``Replace`` in the same transaction rewrites covers the new text.

Refusals
    The ``expect`` text of a ``Replace`` / ``Delete`` must equal the text of the
    range; a mismatch refuses that operation (never a guess). Other refusals:
    unknown paragraph or comment, range outside the paragraph, text with a
    newline (one paragraph per ``InsertParagraph``), nowhere to attach inserted
    text (a paragraph with no text near the range), an empty range left after
    a rewrite, a ``Bind`` whose range overlaps an edit in the same transaction,
    cuts a field, or crosses a tracked-change boundary, a duplicate anchor id,
    an edit that touches a field result, a comment whose field leaves no text
    in its first paragraph.
    ``Move`` and ``Unbind`` raise ``NotImplementedError``.

Known limits
    ``commentsIds.xml`` (durable ids) is not updated for new comments; Word
    regenerates it. The comment date is UTC with a ``Z``; whetstone's tracked
    changes carry a naive local timestamp (its own choice, left alone).
"""

