"""Where the fields of a document sit, in the coordinates of the view text.

A field's result (the text Word shows) is regenerated by Word, Zotero or
EndNote on refresh, so the writer must never put an edit, a comment marker or
a content control inside one. This module only locates fields; the writer
decides what to do with them.

``Field.start`` / ``stop`` are the offsets of the field's result in the global
atom text (paragraphs joined by one newline, as ``document_atoms`` reads it).
``begin`` / ``end`` are the elements that bound the whole field: for a complex
field the ``w:r`` holding the ``begin`` / ``end`` ``fldChar``, for ``w:fldSimple``
the element itself. A field with no ``separate`` has no result (``sep`` is
None and ``start == stop``).
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

from andamentum.docx_edit import EXCLUDED_SUBTREES, Atom

from .ooxml import w


@dataclass(frozen=True)
class Field:
    begin: Any
    end: Any
    sep: Any | None
    start: int
    stop: int

    @property
    def simple(self) -> bool:
        return self.begin is self.end


_COUNTED = frozenset({w("t"), w("br"), w("tab")})
_FLDCHAR = w("fldChar")
_FLDSIMPLE = w("fldSimple")


def fields_in(paragraphs: Sequence[Any], atoms: Sequence[Atom]) -> list[Field]:
    """Every field of *paragraphs*, outer before inner within a start position.

    *atoms* must be ``document_atoms(paragraphs)`` for the same tree.
    """
    weight = Counter(id(a.element) for a in atoms if a.element is not None)
    found: list[Field] = []
    stack: list[list[Any]] = []  # [begin run, separate run | None, result start | None]
    count = 0

    def walk(node: Any) -> None:
        nonlocal count
        for child in node:
            tag = child.tag
            if not isinstance(tag, str) or tag in EXCLUDED_SUBTREES:
                continue
            if tag in _COUNTED:
                count += weight.get(id(child), 0)
            elif tag == _FLDSIMPLE:
                start = count
                walk(child)
                found.append(Field(child, child, None, start, count))
            elif tag == _FLDCHAR:
                kind = child.get(w("fldCharType"))
                run = child.getparent()
                if kind == "begin":
                    stack.append([run, None, None])
                elif kind == "separate" and stack:
                    stack[-1][1] = run
                    stack[-1][2] = count
                elif kind == "end" and stack:
                    begin, sep, start = stack.pop()
                    found.append(
                        Field(
                            begin,
                            run,
                            sep,
                            count if start is None else start,
                            count,
                        )
                    )
            else:
                walk(child)

    for index, paragraph in enumerate(paragraphs):
        if index > 0:
            count += 1  # the paragraph break between two paragraphs
        walk(paragraph)
    found.sort(key=lambda f: (f.start, -f.stop))
    return found


def overlapping(fields: Sequence[Field], start: int, stop: int) -> list[Field]:
    """Fields with a result that shares at least one character with the range."""
    return [f for f in fields if f.start < stop and start < f.stop]


def widen_over_fields(
    fields: Sequence[Field], start: int, stop: int
) -> tuple[int, int]:
    """The smallest range holding ``[start, stop)`` and every result it touches."""
    changed = True
    while changed:
        changed = False
        for f in overlapping(fields, start, stop):
            if f.start < start or f.stop > stop:
                start, stop = min(start, f.start), max(stop, f.stop)
                changed = True
    return start, stop
