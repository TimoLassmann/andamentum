"""M0 survival tests: does the spike document keep its anchors through other tools?

Three tools: python-docx open and save, LibreOffice headless conversion, and
whetstone's ``open_source`` projection (read-only: the question is whether the
reviewer's text includes what sits inside content controls). Each result is
the harness reader's probe of the file that came back.
"""

from __future__ import annotations

import asyncio
import shutil
import subprocess
from pathlib import Path

from pydantic import BaseModel, ConfigDict

from .make import SPIKE_CLAIM_TEXT, SPIKE_NUMBER_TEXT, make_spike_docx
from .probe import Finding, ProbeReport, evaluate, probe

# Found on PATH (Homebrew, apt and the macOS app all install ``soffice``); "" when absent.
SOFFICE = shutil.which("soffice") or ""


class ToolResult(BaseModel):
    """A file read back after one tool handled it, or why the tool did not run."""

    model_config = ConfigDict(arbitrary_types_allowed=True)

    path: str | None = None
    report: ProbeReport | None = None
    findings: list[Finding] = []
    skipped: str | None = None


class ProjectionResult(BaseModel):
    number_in_text: bool
    claim_in_text: bool
    characters: int


class SurvivalResults(BaseModel):
    original: ToolResult
    python_docx: ToolResult
    libreoffice: ToolResult
    whetstone: ProjectionResult


def python_docx_roundtrip(source: Path, output: Path) -> Path:
    """Open with python-docx and save, touching nothing."""
    from docx import Document  # python-docx

    Document(str(source)).save(str(output))
    return output


def libreoffice_roundtrip(
    source: Path, *, workdir: Path, soffice: str = SOFFICE
) -> Path:
    """Convert *source* to docx with headless LibreOffice, into ``workdir/lo-out``.

    A private profile directory under *workdir* keeps LibreOffice from
    writing into the user's home.
    """
    outdir = workdir / "lo-out"
    outdir.mkdir(parents=True, exist_ok=True)
    staged = workdir / "lo-in" / source.name
    staged.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(source, staged)
    profile = (workdir / "lo-profile").resolve()
    completed = subprocess.run(
        [
            soffice,
            f"-env:UserInstallation=file://{profile}",
            "--headless",
            "--convert-to",
            "docx:MS Word 2007 XML",
            "--outdir",
            str(outdir),
            str(staged),
        ],
        capture_output=True,
        text=True,
        timeout=180,
        check=False,
    )
    result = outdir / source.name
    if completed.returncode != 0 or not result.exists():
        raise RuntimeError(
            f"LibreOffice conversion failed (exit {completed.returncode}): "
            f"{completed.stdout.strip()} {completed.stderr.strip()}"
        )
    return result


def whetstone_projection(path: Path) -> ProjectionResult:
    """Does whetstone's reviewed text include the text inside the controls?"""
    from andamentum.whetstone import open_source

    async def _open() -> str:
        document = await open_source(str(path))
        try:
            return document.text
        finally:
            document.cleanup()

    text = asyncio.run(_open())
    return ProjectionResult(
        number_in_text=SPIKE_NUMBER_TEXT in text,
        claim_in_text=SPIKE_CLAIM_TEXT in text,
        characters=len(text),
    )


def run_survival(workdir: Path, *, soffice: str = SOFFICE) -> SurvivalResults:
    """Run all three tests in *workdir*."""
    workdir.mkdir(parents=True, exist_ok=True)
    original = make_spike_docx(workdir / "spike.docx")
    roundtripped = python_docx_roundtrip(original, workdir / "spike-python-docx.docx")
    if soffice and Path(soffice).exists():
        libreoffice = _summary(
            libreoffice_roundtrip(original, workdir=workdir, soffice=soffice)
        )
    else:
        libreoffice = ToolResult(skipped=f"{soffice} not found")
    return SurvivalResults(
        original=_summary(original),
        python_docx=_summary(roundtripped),
        libreoffice=libreoffice,
        whetstone=whetstone_projection(original),
    )


def _summary(path: Path) -> ToolResult:
    report = probe(path)
    return ToolResult(path=str(path), report=report, findings=evaluate(report))


def render_report(results: SurvivalResults) -> str:
    """The spike report tables as markdown."""
    lines = [
        "# M0 spike report",
        "",
        "Generated by `andamentum.compose.harness.spike`.",
        "",
    ]
    for tool, entry in (
        ("original", results.original),
        ("python-docx", results.python_docx),
        ("libreoffice", results.libreoffice),
    ):
        lines += [f"## {tool}", ""]
        if entry.skipped is not None:
            lines += [f"Skipped: {entry.skipped}", ""]
            continue
        lines += ["| item | result | detail |", "| --- | --- | --- |"]
        for finding in entry.findings:
            outcome = "survived" if finding.present else "LOST"
            detail = finding.detail.replace("|", "/")
            lines.append(f"| {finding.name} | {outcome} | {detail} |")
        lines.append("")
    projection = results.whetstone
    lines += [
        "## whetstone open_source projection",
        "",
        f"- text inside the number control present: {projection.number_in_text}",
        f"- text inside the claim control present: {projection.claim_in_text}",
        f"- projected characters: {projection.characters}",
        "",
    ]
    return "\n".join(lines)
